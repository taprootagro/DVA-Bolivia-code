/**
 * 从 taprootagrosetting/*.json 组装与 defaultConfig 一致的 JSON，
 * 写入 .tmp-seed.json，并可选更新 supabase/migrations/001_init.sql 中的 app_config 种子。
 *
 * 用法：
 *   node scripts/generate-seed-sql.mjs           # 仅写 .tmp-seed.json / .tmp-seed.sql
 *   node scripts/generate-seed-sql.mjs --write-init  # 同时替换 001_init.sql 内 INSERT 块
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const settingDir = path.join(root, 'taprootagrosetting');
const initSqlPath = path.join(root, 'supabase', 'migrations', '001_init.sql');

function readJson(file) {
  return JSON.parse(fs.readFileSync(path.join(settingDir, file), 'utf8'));
}

const home = readJson('home.json');
const market = readJson('market.json');
const app = readJson('app.json');
const chat = readJson('chat.json');
const legal = readJson('legal.json');
const ai = readJson('ai.json');
const push = readJson('push.json');
const auth = readJson('auth.json');
const live = readJson('live.json');
const backend = readJson('backend.json');

const seed = {
  banners: home.banners,
  navigation: home.navigation,
  liveStreams: home.liveStreams,
  articles: home.articles,
  videoFeed: home.videoFeed,
  homeIcons: home.homeIcons,
  currencySymbol: market.currencySymbol,
  marketPage: market.marketPage,
  profileEditCooldownSeconds:
    typeof app.profileEditCooldownSeconds === 'number'
      ? Math.max(0, Math.floor(app.profileEditCooldownSeconds))
      : 300,
  appBranding: app.appBranding,
  splashScreen: app.splashScreen,
  desktopIcon: app.desktopIcon,
  filing: app.filing,
  communityUiMode: chat.communityUiMode ?? 'farmer',
  chatContact: chat.chatContact,
  userProfile: chat.userProfile,
  aboutUs: legal.aboutUs,
  privacyPolicy: legal.privacyPolicy,
  termsOfService: legal.termsOfService,
  technicalSupport: legal.technicalSupport,
  aiModelConfig: ai.aiModelConfig,
  cloudAIConfig: ai.cloudAIConfig,
  pushConfig: push.pushConfig,
  pushProvidersConfig: push.pushProvidersConfig,
  loginConfig: auth.loginConfig,
  liveShareConfig: live.liveShareConfig,
  liveNavigationConfig: live.liveNavigationConfig,
  backendProxyConfig: backend.backendProxyConfig,
};

const jsonStr = JSON.stringify(seed, null, 6);
/** PostgreSQL dollar-quote：避免 JSON 内含 `'` 时破坏 SQL 字符串 */
const dq = '$taproot_app_config_seed$';
const insertBlock = `INSERT INTO app_config (id, config, version, updated_by)
VALUES (
  'main',
  ${dq}
${jsonStr}
${dq}::jsonb,
  1,
  'init-script'
)
ON CONFLICT (id) DO NOTHING;`;

fs.writeFileSync(path.join(root, '.tmp-seed.json'), jsonStr, 'utf8');
console.log('Wrote .tmp-seed.json');

fs.writeFileSync(
  path.join(root, '.tmp-seed.sql'),
  `-- Generated by scripts/generate-seed-sql.mjs — do not edit by hand; re-run script after taprootagrosetting/*.json changes.\n\n${insertBlock}\n`,
  'utf8',
);
console.log('Wrote .tmp-seed.sql');

const writeInit = process.argv.includes('--write-init');
if (writeInit) {
  const sql = fs.readFileSync(initSqlPath, 'utf8');
  const startRe =
    /INSERT INTO app_config \(id, config, version, updated_by\)\s*\nVALUES\s*\(/;
  const endRe = /\nON CONFLICT \(id\) DO NOTHING;/;
  const startMatch = sql.match(startRe);
  const endMatch = sql.match(endRe);
  if (!startMatch || startMatch.index === undefined || !endMatch || endMatch.index === undefined) {
    console.error('Could not find INSERT INTO app_config ... ON CONFLICT block in 001_init.sql');
    process.exit(1);
  }
  const startIdx = startMatch.index;
  const endIdx = endMatch.index + endMatch[0].length;
  const next = sql.slice(0, startIdx) + insertBlock + sql.slice(endIdx);
  fs.writeFileSync(initSqlPath, next, 'utf8');
  console.log('Updated supabase/migrations/001_init.sql app_config seed');
}

console.log('Done.');
